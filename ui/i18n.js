export function t(key, values = {}) {
  const template = catalogs[language][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values,name) ? String(values[name]) : match);
}
export function plural(value, one, other, values = {}) {
  return t(new Intl.PluralRules(locale()).select(value) === 'one' ? one : other, values);
}
export function applyTranslations(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const attribute of ['aria-label','placeholder']) {
    for (const element of root.querySelectorAll('[data-i18n-'+attribute+']')) element.setAttribute(attribute,t(element.getAttribute('data-i18n-'+attribute)));
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
    const select = document.getElementById('language-select'); if(select) select.value = language;
  }
}
export function setLanguage(value) {
  if (value !== 'de' && value !== 'en') return false;
  const changed = language !== value;
  language = value; persist();
  if (typeof document !== 'undefined') applyTranslations();
  if (changed && typeof window !== 'undefined') window.dispatchEvent(new Event('flightdeck-languagechange'));
  return changed;
}
