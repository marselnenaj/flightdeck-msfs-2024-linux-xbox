const STORAGE_KEY = 'flightdeck-language';
export function chooseLanguage({query, stored, browser} = {}) {
  if (query === 'de' || query === 'en') return query;
  if (stored === 'de' || stored === 'en') return stored;
  return /^de(?:-|$)/i.test(browser || '') ? 'de' : 'en';
}
let stored;
try { if(typeof window !== 'undefined') stored = window.localStorage?.getItem(STORAGE_KEY); } catch { /* Optional storage. */ }
const query = typeof location === 'undefined' ? null : new URLSearchParams(location.search).get('lang');
let language = chooseLanguage({query, stored, browser:typeof document === 'undefined' ? 'de' : globalThis.navigator?.language});
function persist() { try { if(typeof window !== 'undefined') window.localStorage?.setItem(STORAGE_KEY, language); } catch { /* Private browsing remains usable. */ } }
if (query === 'de' || query === 'en') {
  persist();
  // A CLI link is a one-time override, not a permanent veto of later choices.
  if(typeof window !== 'undefined') {
    const url = new URL(window.location.href);url.searchParams.delete('lang');
    window.history.replaceState(window.history.state,'',url);
  }
}
export const getLanguage = () => language;
export const locale = () => language === 'de' ? 'de-AT' : 'en-GB';
export function t(key, values = {}) {
  const template = catalogs[language][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values,name) ? String(values[name]) : match);
}
export function plural(value, one, other, values = {}) {
  return t(new Intl.PluralRules(locale()).select(value) === 'one' ? one : other, values);
}
export function applyTranslations(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const attribute of ['aria-label','placeholder']) {
    for (const element of root.querySelectorAll('[data-i18n-'+attribute+']')) element.setAttribute(attribute,t(element.getAttribute('data-i18n-'+attribute)));
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
    const select = document.getElementById('language-select'); if(select) select.value = language;
  }
}
export function setLanguage(value) {
  if (value !== 'de' && value !== 'en') return false;
  const changed = language !== value;
  language = value; persist();
  if (typeof document !== 'undefined') applyTranslations();
  if (changed && typeof window !== 'undefined') window.dispatchEvent(new Event('flightdeck-languagechange'));
  return changed;
}
