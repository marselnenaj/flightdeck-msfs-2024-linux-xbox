try { if(typeof window !== 'undefined') stored = window.localStorage?.getItem(STORAGE_KEY); } catch { /* Optional storage. */ }
const query = typeof location === 'undefined' ? null : new URLSearchParams(location.search).get('lang');
let language = chooseLanguage({query, stored, browser:typeof document === 'undefined' ? 'de' : globalThis.navigator?.language});
function persist() { try { if(typeof window !== 'undefined') window.localStorage?.setItem(STORAGE_KEY, language); } catch { /* Private browsing remains usable. */ } }
