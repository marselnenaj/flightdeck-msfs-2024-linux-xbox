export function chooseLanguage({query, stored, browser} = {}) {
  if (query === 'de' || query === 'en') return query;
  if (stored === 'de' || stored === 'en') return stored;
  return /^de(?:-|$)/i.test(browser || '') ? 'de' : 'en';
}
